package io.github.genkidoudou.common.desensitization;

/**
 * 脱敏类型枚举
 *
 * @author QuickBoot
 * @since 2026/03/02
 */
public enum SensitiveType {

    /**
     * 姓名脱敏
     * 规则：保留姓氏，其他用*代替
     * 例如：张三 -> 张*
     */
    NAME,

    /**
     * 身份证号脱敏
     * 规则：保留前6位和后4位
     * 例如：110101199001011234 -> 110101********1234
     */
    ID_CARD,

    /**
     * 手机号脱敏
     * 规则：保留前3位和后4位
     * 例如：13812345678 -> 138****5678
     */
    MOBILE,

    /**
     * 银行卡号脱敏
     * 规则：保留前4位和后4位
     * 例如：6222021234567890123 -> 6222***********0123
     */
    BANK_CARD,

    /**
     * 邮箱脱敏
     * 规则：保留@前的前2位和@后的域名
     * 例如：example@gmail.com -> ex****@gmail.com
     */
    EMAIL,

    /**
     * 地址脱敏
     * 规则：保留省市，其他用*代替
     * 例如：北京市朝阳区某某街道123号 -> 北京市朝阳区******
     */
    ADDRESS,

    /**
     * 密码脱敏
     * 规则：全部用*代替
     * 例如：123456 -> ******
     */
    PASSWORD,

    /**
     * 自定义脱敏
     * 需要配合 strategy 属性使用
     */
    CUSTOM
}
